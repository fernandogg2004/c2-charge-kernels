"""Generate the Lean modules that check a certificate with the kernel only (no native_decide).

Usage: python export_lean.py CERT.json OUTDIR NAME BOUND [file_max] [shard_max] [procs]
  e.g. python export_lean.py pt900d_cert.json ../lean/ChargeKernel Pt900 7453/2000

Writes OUTDIR/NAME/{Data,F###,Top,V1,Final}.lean, modules.txt and value.txt.
Every leaf value is first computed here (checker_nat.py) and asserted nonnegative; the Lean kernel
recomputes all of them independently (`decide +kernel`) and `nChk_spec` transfers them exactly to
the rational checker of ChargeKernel/CertSym.lean.
"""
import sys, os
from fractions import Fraction as Q
from multiprocessing import Pool
import checker_rational as RL, checker_nat as N

ER2, ES2 = 8, 14      # scales of the integral tree (r in [0, 64], s in [0, 1])
ER1, ES1 = 10, 12     # scales of the diamond tree (r, s in [0, 1])
G = {}
HDR = ("/-\nCopyright (c) 2026 Fernando. All rights reserved.\n"
       "Released under Apache 2.0 license as described in the file LICENSE.\nAuthors: Fernando\n-/\n")

def init(cl, Ai, Ci): G.update(cl=cl, Ai=Ai, Ci=Ci)

def cellN(cell, er, es):
    r0, r1, s0, s1 = cell
    v = [r0 * 2 ** er, r1 * 2 ** er, s0 * 2 ** es, s1 * 2 ** es]
    assert all(x.denominator == 1 for x in v), cell
    return tuple(int(x) for x in v)

def leafvals(job):
    t, cell, path = job
    out = {}
    def go(t, cell, path):
        if t is None:
            v, _ = N.nLeaf(ER2, ES2, G["Ai"], G["Ci"], G["cl"], *cellN(cell, ER2, ES2))
            assert v >= 0; out[path] = v; return v
        tot = 0
        for k, (sub, ch) in enumerate(zip(t, RL.children(*cell))): tot += go(sub, ch, path + str(k))
        out[path] = tot; return tot
    go(t, cell, path); return out

def v1check(t, cell, a, c, m, L, mN, mD):
    if t is None:
        R0, R1, S0, S1 = cellN(cell, ER1, ES1)
        U0, U1 = R0 * S0 + N.OFF, R1 * S1 + N.OFF
        V0, V1 = R0 * (2 ** ES1 - S1) + N.OFF, R1 * (2 ** ES1 - S0) + N.OFF
        smin, smax, pos = N.pass1(U0, U1, V0, V1, G["cl"])
        ok = pos and 0 < R1 and R1 * (mD * (G["Ci"] + smax) + mN * 2 ** 30) <= G["Ai"] * mD * 2 ** ER1
        assert ok == RL.v1leaf(a, c, m, 1, 1, L, *cell), cell
        return ok
    return all(v1check(sub, ch, a, c, m, L, mN, mD) for sub, ch in zip(t, RL.children(*cell)))

def bits(t): return "0" if t is None else "1" + "".join(bits(s) for s in t)
def nleaves(t): return 1 if t is None else sum(nleaves(s) for s in t)

def subtrees(t, cell, path, depth):
    if depth == 0 or t is None: return [(t, cell, path)]
    out = []
    for k, (sub, ch) in enumerate(zip(t, RL.children(*cell))): out += subtrees(sub, ch, path + str(k), depth - 1)
    return out

def qlit(x):
    return f"({x.numerator} : ℚ)" if x.denominator == 1 else f"({x.numerator} / {x.denominator} : ℚ)"

def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f: f.write(text)

if __name__ == "__main__":
    fn, outdir, name, bnd = sys.argv[1:5]
    FMAX = int(sys.argv[5]) if len(sys.argv) > 5 else 6000
    SMAX = int(sys.argv[6]) if len(sys.argv) > 6 else 32
    procs = int(sys.argv[7]) if len(sys.argv) > 7 else os.cpu_count()
    a, c, m, R, L, T1, T2 = RL.read_cert(fn)
    assert R == 64
    mN, mD = m.numerator, m.denominator
    bn, bd = (int(x) for x in bnd.split("/"))
    cl = N.encode(L); Ai, Ci = a * 2 ** 30, c * 2 ** 30
    assert Ai.denominator == 1 and Ci.denominator == 1; Ai, Ci = int(Ai), int(Ci)
    t2, t1 = RL.parse(T2), RL.parse(T1)
    root2 = (Q(0), Q(64), Q(0), Q(1)); root1 = (Q(0), Q(1), Q(0), Q(1))
    V = {}
    with Pool(procs, initializer=init, initargs=(cl, Ai, Ci)) as P:
        for d in P.map(leafvals, subtrees(t2, root2, "", 4), chunksize=1): V.update(d)
    init(cl, Ai, Ci)
    v1ok = v1check(t1, root1, a, c, m, L, mN, mD)
    def total(t, path):
        if path not in V: V[path] = sum(total(s, path + str(k)) for k, s in enumerate(t))
        return V[path]
    Vr = total(t2, "")
    X = 2 * ES2 + 3 * ER2 + 53; D = 6 * 2 ** X
    bound = 4 * Q(Vr, D) / (2 * m)
    print(f"T2: {nleaves(t2)} leaves, quadrant value {float(Q(Vr, D)):.10f}; c2 <= {float(bound):.6f} "
          f"<= {bn}/{bd}: {bound <= Q(bn, bd)};  diamond check: {v1ok}", flush=True)
    assert v1ok and bound <= Q(bn, bd)

    od = os.path.join(outdir, name); os.makedirs(od, exist_ok=True)
    mod = f"ChargeKernel.{name}"; ns = f"ChargeKernel.{name}"
    body = "".join(f"NCL.cons {P} {Qn} {B} <| " for P, Qn, B in cl) + "NCL.nil"
    write(os.path.join(od, "Data.lean"), HDR + "module\n\npublic import ChargeKernel.CertNat\n\n"
          f"/-! Generated by `certificate/export_lean.py` from `{os.path.basename(fn)}`: the encoded charges and\n"
          "constants (`a = kAi / 2^30`, `c = kCi / 2^30`, positions `(P - 2^32) / 2^22`, strengths `B / 2^52`). -/\n\n"
          f"@[expose] public section\n\nnamespace {ns}\nopen CenteredMaximal.General\n\n"
          f"def kAi : Nat := {Ai}\ndef kCi : Nat := {Ci}\nset_option maxRecDepth 100000 in\ndef kL : NCL := {body}\n\nend {ns}\n")

    def nm(path): return "r" + path
    def cellstr(cell): return " ".join(str(x) for x in cellN(cell, ER2, ES2))
    def emit_join(lines, path, cell):
        c = [nm(path + str(k)) for k in range(4)]
        lines.append(f"def t_{nm(path)} : NTree := .node " + " ".join(f"t_{x}" for x in c))
        lines.append(f"theorem k_{nm(path)} : nChk 8 14 kAi kCi kL t_{nm(path)} {cellstr(cell)} = some {V[path]} :=\n"
                     "  nChk_node rfl rfl " + " ".join(f"k_{x}" for x in c) + " rfl\n")
    def emit_node(lines, t, cell, path):
        if t is None or nleaves(t) <= SMAX:
            lines.append(f'def t_{nm(path)} : NTree := NTree.ofString "{bits(t)}"')
            lines.append(f"theorem k_{nm(path)} : nChk 8 14 kAi kCi kL t_{nm(path)} {cellstr(cell)} = some {V[path]} := by\n"
                         "  decide +kernel\n")
            return
        ch = RL.children(*cell)
        for k in range(4): emit_node(lines, t[k], ch[k], path + str(k))
        emit_join(lines, path, cell)
    files = []
    def plan(t, cell, path):
        if t is None or nleaves(t) <= FMAX: files.append((t, cell, path)); return
        for k, (sub, ch) in enumerate(zip(t, RL.children(*cell))): plan(sub, ch, path + str(k))
    plan(t2, root2, "")
    mods = []
    for i, (t, cell, path) in enumerate(files):
        lines = []; emit_node(lines, t, cell, path)
        fname = f"F{i:03d}"; mods.append(f"{mod}.{fname}")
        write(os.path.join(od, fname + ".lean"), HDR + f"module\n\npublic import {mod}.Data\n\n/-! Generated: kernel checks of "
              f"the subtree `{path or 'root'}` ({nleaves(t)} leaves). -/\n\n@[expose] public section\n\nnamespace {ns}\n"
              "open CenteredMaximal.General\n\nset_option maxRecDepth 100000\n\n" + "\n".join(lines) + f"\nend {ns}\n")
    froots = {p for _, _, p in files}
    top = []
    def assemble(t, cell, path):
        if path in froots: return
        for k, (sub, ch) in enumerate(zip(t, RL.children(*cell))): assemble(sub, ch, path + str(k))
        emit_join(top, path, cell)
    assemble(t2, root2, "")
    write(os.path.join(od, "Top.lean"), HDR + "module\n\n" + "".join(f"public import {x}\n" for x in mods) +
          f"\n/-! Generated: assembly of the subtree checks. -/\n\n@[expose] public section\n\nnamespace {ns}\n"
          "open CenteredMaximal.General\n\n" + "\n".join(top) + f"\nend {ns}\n")
    v1 = []
    def cell1(cell): return " ".join(str(x) for x in cellN(cell, ER1, ES1))
    def emit_v1(t, cell, path):
        if t is None or nleaves(t) <= 4 * SMAX:
            v1.append(f'def u_{nm(path)} : NTree := NTree.ofString "{bits(t)}"')
            v1.append(f"theorem w_{nm(path)} : nV1 10 12 kAi kCi {mN} {mD} kL u_{nm(path)} {cell1(cell)} = true := by\n"
                      "  decide +kernel\n")
            return
        ch = RL.children(*cell)
        for k in range(4): emit_v1(t[k], ch[k], path + str(k))
        c = [nm(path + str(k)) for k in range(4)]
        v1.append(f"def u_{nm(path)} : NTree := .node " + " ".join(f"u_{x}" for x in c))
        v1.append(f"theorem w_{nm(path)} : nV1 10 12 kAi kCi {mN} {mD} kL u_{nm(path)} {cell1(cell)} = true :=\n"
                  "  nV1_node rfl rfl " + " ".join(f"w_{x}" for x in c) + "\n")
    emit_v1(t1, root1, "")
    write(os.path.join(od, "V1.lean"), HDR + f"module\n\npublic import {mod}.Data\n\n/-! Generated: kernel check of the "
          f"diamond tree. -/\n\n@[expose] public section\n\nnamespace {ns}\nopen CenteredMaximal.General\n\n"
          "set_option maxRecDepth 100000\n\n" + "\n".join(v1) + f"\nend {ns}\n")
    Lsrc = ",\n".join(f"  ⟨{qlit(p)}, {qlit(q)}, {qlit(b)}⟩" for p, q, b in L)
    final = HDR + f"""module

public import {mod}.Top
public import {mod}.V1
public import ChargeKernel.CertNatSound
public import ChargeKernel.CertBridgeSym

/-!
# c₂ ≤ {bn}/{bd}, checked by the kernel only

Generated by `certificate/export_lean.py` from `{os.path.basename(fn)}` ({len(L)} charges). The two
quadtree checks are evaluated by the kernel on natural numbers (modules `{name}.F###`, `{name}.Top`,
`{name}.V1`, all `decide +kernel`), and `nChk_spec` / `nV1_spec` transfer them exactly to the rational
checker. The soundness theorem `c2_le_of_cert_sym` then gives the bound. No `native_decide` is used.
-/

@[expose] public section

namespace {ns}
open CenteredMaximal CenteredMaximal.General

/-- The decoded charges, as rationals. -/
def kLq : List Chg := [
{Lsrc}]

set_option maxRecDepth 100000 in
theorem kL_toList : kL.toList = kLq := by decide +kernel

theorem kq_nonneg : allNonneg kLq = true := by decide +kernel
theorem kq_permU : (kLq.map Chg.flipU).Perm kLq := by decide +kernel
theorem kq_permV : (kLq.map Chg.flipV).Perm kLq := by decide +kernel

/-- **Main theorem.** The weak type `(1, 1)` constant of the centred maximal operator over squares
in the plane is at most `{bn}/{bd}`. -/
theorem weakTypeConstant_two_le : weakTypeConstant 2 ≤ ENNReal.ofReal ({bn} / {bd}) := by
  have h2 := nChk_spec (Ai := kAi) (Ci := kCi) (l := kL) t_r 0 16384 0 16384 {Vr}
    (by norm_num) (by norm_num) (by norm_num) k_r
  have h1 := nV1_spec (Ai := kAi) (Ci := kCi) (mN := {mN}) (mD := {mD}) (by norm_num) (l := kL) u_r
    0 1024 0 4096 (by norm_num) (by norm_num) (by norm_num) w_r
  rw [kL_toList] at h1 h2
  have z8 : ((0 : ℕ) : ℚ) / 2 ^ 8 = 0 := by norm_num
  have z10 : ((0 : ℕ) : ℚ) / 2 ^ 10 = 0 := by norm_num
  have z12 : ((0 : ℕ) : ℚ) / 2 ^ 12 = 0 := by norm_num
  have z14 : ((0 : ℕ) : ℚ) / 2 ^ 14 = 0 := by norm_num
  have r64 : ((16384 : ℕ) : ℚ) / 2 ^ 8 = 64 := by norm_num
  have s1 : ((16384 : ℕ) : ℚ) / 2 ^ 14 = 1 := by norm_num
  have r1 : ((1024 : ℕ) : ℚ) / 2 ^ 10 = 1 := by norm_num
  have t1 : ((4096 : ℕ) : ℚ) / 2 ^ 12 = 1 := by norm_num
  have mm : (({mN} : ℕ) : ℚ) / (({mD} : ℕ) : ℚ) = {mN} / {mD} := by norm_num
  rw [z8, z14, r64, s1] at h2
  rw [z10, z12, r1, t1, mm] at h1
  obtain ⟨o2, e2⟩ := v2chk_spec _ _ _ _ _ _ _ _ _ _ _ h2
  have ha : (0 : ℚ) ≤ (kAi : ℚ) / 2 ^ 30 := by positivity
  have hc : (0 : ℚ) < (kCi : ℚ) / 2 ^ 30 := by unfold kCi; norm_num
  have haR : (kAi : ℚ) / 2 ^ 30 ≤ 64 * ((kCi : ℚ) / 2 ^ 30) := by unfold kAi kCi; norm_num
  have hfin := c2_le_of_cert_sym (m := {mN} / {mD}) (R := 64) (Bnd := {bn} / {bd})
    (Q := (({Vr} : ℤ) : ℚ) / (6 * 2 ^ 105))
    kq_nonneg ha hc (by norm_num) (by norm_num) haR kq_permU kq_permV h1 ⟨o2, e2.le⟩ (by norm_num)
  rw [show (((({bn} : ℚ) / {bd} : ℚ)) : ℝ) = {bn} / {bd} by norm_num] at hfin
  exact hfin

end {ns}
"""
    write(os.path.join(od, "Final.lean"), final)
    write(os.path.join(od, "modules.txt"), "\n".join(mods) + "\n")
    write(os.path.join(od, "value.txt"), f"{Vr}\n{D}\n")
    print(f"{len(files)} shard files; top joins: {sum(1 for l in top if l.startswith('theorem'))}")
